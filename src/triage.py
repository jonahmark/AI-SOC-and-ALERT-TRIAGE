"""Alert triage state: investigation statuses and analyst notes.

Two backends, selected by configuration:
- JSON files beside the alert CSV (default; single-instance behaviour unchanged)
- a private PostgreSQL database, so triage survives redeploys and is shared by
  every instance pointing at it (the hosted deployment).

Alert records themselves stay in alerts.csv; only the analyst workflow state
moves. A shared database is never pruned or cleared when alerts are regenerated
or cleared locally - one instance must not destroy another's triage work.
"""
from __future__ import annotations

import hashlib
import json
import os
from datetime import datetime, timezone
from pathlib import Path

import config
from src.env import load_dotenv_defaults
from src.postgres import PostgresStore

load_dotenv_defaults()

STATUS_FILE = config.ALERT_STATUS_FILE
NOTES_FILE = config.ALERT_NOTES_FILE

# A triage-only URL shares workflow state while local authentication stays on
# SQLite. Unset, it falls back to the auth database so the hosted deployment
# needs no extra secret.
def _configured_url() -> str:
    return (os.environ.get("AI_SOC_TRIAGE_DATABASE_URL", "").strip()
            or os.environ.get("AI_SOC_AUTH_DATABASE_URL", "").strip())


TRIAGE_DATABASE_URL = _configured_url()

_TRIAGE_SCHEMA = """
CREATE TABLE IF NOT EXISTS alert_statuses (
    alert_id   TEXT PRIMARY KEY,
    status     TEXT NOT NULL,
    updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS alert_notes (
    id         INTEGER PRIMARY KEY AUTOINCREMENT,
    alert_id   TEXT NOT NULL,
    author     TEXT NOT NULL,
    note_text  TEXT NOT NULL,
    created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_alert_notes_alert ON alert_notes(alert_id, id);
"""

_POSTGRES_TRIAGE_SCHEMA = _TRIAGE_SCHEMA.replace(
    "INTEGER PRIMARY KEY AUTOINCREMENT",
    "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
)
_TRIAGE_SCHEMA_LOCK_ID = 0x4149534F43545249  # Fixed, process-independent triage DDL lock.


def _utc_now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


class FileTriageState:
    """Workflow state in JSON files beside the alert CSV."""

    shared = False

    def __init__(self, status_file: Path | str = STATUS_FILE,
                 notes_file: Path | str = NOTES_FILE):
        self.status_file = Path(status_file)
        self.notes_file = Path(notes_file)

    def statuses(self) -> dict:
        if self.status_file.exists():
            return json.loads(self.status_file.read_text())
        return {}

    def set_status(self, alert_id: str, status: str) -> None:
        statuses = self.statuses()
        statuses[alert_id] = status
        self._write_json(self.status_file, statuses)

    def notes(self, alert_id: str) -> list:
        return list(self._load_notes().get(alert_id, []))

    def add_note(self, alert_id: str, entry: dict) -> None:
        notes = self._load_notes()
        notes.setdefault(alert_id, []).append(entry)
        self._write_json(self.notes_file, notes)

    def note_counts(self) -> dict:
        return {k: len(v) for k, v in self._load_notes().items() if v}

    def retain(self, known_ids: set) -> None:
        """Discard workflow state for alerts that are no longer stored."""
        self._write_json(self.status_file, {
            k: v for k, v in self.statuses().items() if k in known_ids})
        notes = {k: v for k, v in self._load_notes().items() if k in known_ids}
        if not notes:
            if self.notes_file.exists():
                self.notes_file.unlink()
            return
        self._write_json(self.notes_file, notes)

    def clear(self) -> None:
        for path in (self.status_file, self.notes_file):
            if path.exists():
                path.unlink()

    def _load_notes(self) -> dict:
        if self.notes_file.exists():
            try:
                return json.loads(self.notes_file.read_text())
            except json.JSONDecodeError:
                return {}
        return {}

    @staticmethod
    def _write_json(path: Path, payload: dict) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(payload, indent=2))


class PostgresTriageStore(PostgresStore):
    """Triage tables in private PostgreSQL, bootstrapped on first use."""

    def __init__(self, database_url: str):
        super().__init__(database_url)
        # CREATE IF NOT EXISTS alone is not safe against concurrent catalog
        # creation. Serialize all DDL across processes until this txn commits.
        with self.transaction() as conn:
            conn.execute("SELECT pg_advisory_xact_lock(%s)",
                         (_TRIAGE_SCHEMA_LOCK_ID,))
            for statement in _POSTGRES_TRIAGE_SCHEMA.split(";"):
                if statement.strip():
                    conn.execute(statement)


class DatabaseTriageState:
    """Workflow state in a database shared by every instance pointing at it.

    Rows outlive any single alert queue: alert IDs are regenerated per run, so
    retain()/clear() deliberately do nothing here. Reads are matched against the
    current alert IDs, which keeps superseded rows invisible instead of letting
    one instance delete another instance's investigation history.
    """

    shared = True

    def __init__(self, store):
        self._store = store

    def statuses(self) -> dict:
        return {row["alert_id"]: row["status"] for row in self._store.query(
            "SELECT alert_id, status FROM alert_statuses")}

    def set_status(self, alert_id: str, status: str) -> None:
        self._store.execute(
            "INSERT INTO alert_statuses (alert_id, status, updated_at) "
            "VALUES (?, ?, ?) ON CONFLICT (alert_id) DO UPDATE SET "
            "status = excluded.status, updated_at = excluded.updated_at",
            (alert_id, status, _utc_now()),
        )

    def notes(self, alert_id: str) -> list:
        rows = self._store.query(
            "SELECT author, note_text, created_at FROM alert_notes "
            "WHERE alert_id = ? ORDER BY id", (alert_id,))
        return [{"alert_id": alert_id, "author": row["author"],
                 "text": row["note_text"], "created_at": row["created_at"]}
                for row in rows]

    def add_note(self, alert_id: str, entry: dict) -> None:
        self._store.execute(
            "INSERT INTO alert_notes (alert_id, author, note_text, created_at) "
            "VALUES (?, ?, ?, ?)",
            (alert_id, entry["author"], entry["text"], entry["created_at"]),
        )

    def note_counts(self) -> dict:
        return {row["alert_id"]: int(row["n"]) for row in self._store.query(
            "SELECT alert_id, COUNT(*) AS n FROM alert_notes GROUP BY alert_id")}

    def retain(self, known_ids: set) -> None:
        return

    def clear(self) -> None:
        return


_STATES: dict[str, DatabaseTriageState] = {}


def get_state(status_file: Path | str = STATUS_FILE,
              notes_file: Path | str = NOTES_FILE):
    """Read configuration at call time; cache database state per target.

    A configured database fails closed: there is no silent fallback to JSON,
    which would split workflow state across two stores. Its URL is never a
    literal cache key.
    """
    database_url = TRIAGE_DATABASE_URL
    if database_url:
        key = hashlib.sha256(database_url.encode("utf-8")).hexdigest()
        if key not in _STATES:
            _STATES[key] = DatabaseTriageState(PostgresTriageStore(database_url))
        return _STATES[key]
    return FileTriageState(status_file, notes_file)


def reset_state_registry() -> None:
    _STATES.clear()